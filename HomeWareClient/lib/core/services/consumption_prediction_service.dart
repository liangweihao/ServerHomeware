import 'package:drift/drift.dart';
import '../../data/database/app_database.dart';

/// 消耗预测服务
/// 用于计算物品的日均消耗量和预计用完日期
class ConsumptionPredictionService {
  final AppDatabase _db;

  ConsumptionPredictionService(this._db);

  /// 计算日均消耗量
  /// 使用加权平均法，越近的记录权重越高
  Future<double?> calculateAvgDailyConsumption(int itemId) async {
    // 获取该物品所有使用记录（type=1 表示使用）
    final records = await (db.select(db.usageRecords)
          ..where((r) => r.itemId.equals(itemId))
          ..where((r) => r.type.equals(1))
          ..orderBy([(r) => OrderingTerm(expression: r.createdAt)]))
        .get();

    if (records.isEmpty) {
      // 没有使用记录，尝试用购买量和创建时间估算
      final item = await db.getItemById(itemId);
      if (item == null) return null;

      final daysSinceCreated = DateTime.now().difference(item.createdAt).inDays;
      if (daysSinceCreated <= 0) return null;

      final consumed = item.purchaseQuantity - item.currentQuantity;
      if (consumed <= 0) return null;

      return consumed / daysSinceCreated;
    }

    if (records.length < 2) {
      // 只有一条记录，用简单平均
      final first = records.first;
      final daysSinceFirst =
          DateTime.now().difference(first.createdAt).inDays;
      if (daysSinceFirst <= 0) return null;

      return first.quantity / daysSinceFirst;
    }

    // 加权平均法计算
    double weightedSum = 0;
    double weightSum = 0;

    for (int i = 0; i < records.length - 1; i++) {
      final current = records[i];
      final next = records[i + 1];

      final daysBetween = next.createdAt.difference(current.createdAt).inDays;
      if (daysBetween <= 0) continue;

      final rate = current.quantity / daysBetween;
      // 权重：越新的记录权重越高（从 1 开始递增）
      final weight = (i + 1).toDouble();

      weightedSum += rate * weight;
      weightSum += weight;
    }

    if (weightSum == 0) return null;

    return weightedSum / weightSum;
  }

  /// 预测物品用完日期
  Future<DateTime?> predictEmptyDate(Item item, double avgDailyConsumption) async {
    if (avgDailyConsumption <= 0) return null;

    final daysRemaining = item.currentQuantity / avgDailyConsumption;
    return DateTime.now().add(Duration(days: daysRemaining.ceil()));
  }

  /// 更新单个物品的预测数据
  Future<void> updateItemPrediction(int itemId) async {
    final item = await db.getItemById(itemId);
    if (item == null) return;

    // 只预测使用中的物品
    if (item.status != 0) return;

    final avgConsumption = await calculateAvgDailyConsumption(itemId);
    DateTime? emptyDate;

    if (avgConsumption != null && avgConsumption > 0) {
      emptyDate = await predictEmptyDate(item, avgConsumption);
    }

    // 更新物品的预测字段
    await db.updateItem(item.copyWith(
      avgDailyConsumption: Value(avgConsumption),
      predictedEmptyDate: Value(emptyDate),
      updatedAt: DateTime.now(),
    ));
  }

  /// 批量更新所有物品的预测数据
  Future<void> updateAllPredictions() async {
    final items = await db.getAllItems();

    for (final item in items) {
      if (item.status == 0) {
        await updateItemPrediction(item.id);
      }
    }
  }

  /// 自动生成购物清单
  /// 条件：库存 <= 安全库存 或 预计用完日期 <= 7天
  Future<void> autoGenerateShoppingList() async {
    final items = await db.getAllItems();

    for (final item in items) {
      // 只处理使用中的物品
      if (item.status != 0) continue;

      // 检查是否需要自动生成
      bool shouldGenerate = false;

      // 条件1：库存 <= 安全库存
      if (item.currentQuantity <= item.safetyStock) {
        shouldGenerate = true;
      }

      // 条件2：预计用完日期 <= 7天
      if (item.predictedEmptyDate != null) {
        final daysUntilEmpty =
            item.predictedEmptyDate!.difference(DateTime.now()).inDays;
        if (daysUntilEmpty <= 7) {
          shouldGenerate = true;
        }
      }

      if (!shouldGenerate) continue;

      // 检查是否已存在于购物清单
      final existingItems = await db.getShoppingList();
      final exists = existingItems.any((s) {
        final relatedId = s.relatedItemId;
        return relatedId == item.id && s.isPurchased == false;
      });

      if (!exists) {
        // 添加到购物清单
        await db.insertShoppingListItem(
          ShoppingListCompanion.insert(
            name: item.name,
            relatedItemId: Value(item.id),
            quantity: Value(item.purchaseQuantity.toDouble()),
            unit: Value(item.unit),
            estimatedPrice: Value(item.purchasePrice),
            isAutoGenerated: const Value(true),
          ),
        );
      }
    }
  }

  /// 在记录使用后调用，更新预测并可能生成购物清单
  Future<void> onItemUsed(int itemId) async {
    await updateItemPrediction(itemId);
    await autoGenerateShoppingList();
  }

  /// App 启动时调用，批量更新并生成清单
  Future<void> onAppStartup() async {
    await updateAllPredictions();
    await autoGenerateShoppingList();
  }

  // 暴露数据库实例
  AppDatabase get db => _db;
}
