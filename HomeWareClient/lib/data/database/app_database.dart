// 使用记录表
class UsageRecords extends Table {
  IntColumn get id => integer().autoIncrement()();
  IntColumn get itemId => integer()();
  IntColumn get type => integer()(); // 0入库/1使用/2丢弃/3移动/4调整
  RealColumn get quantity => real()();
  RealColumn get remainingQuantity => real()();
  TextColumn get operatorName => text().nullable()();
  TextColumn get notes => text().nullable()();
  DateTimeColumn get createdAt => dateTime().withDefault(currentDateAndTime)();
}

// 购物清单表
class ShoppingList extends Table {
  IntColumn get id => integer().autoIncrement()();
  TextColumn get name => text()();
  IntColumn get relatedItemId => integer().nullable()();
  RealColumn get quantity => real().withDefault(const Constant(1))();
  TextColumn get unit => text().withDefault(const Constant('件'))();
  RealColumn get estimatedPrice => real().nullable()();
  BoolColumn get isPurchased => boolean().withDefault(const Constant(false))();
  BoolColumn get isAutoGenerated => boolean().withDefault(const Constant(false))();
  DateTimeColumn get createdAt => dateTime().withDefault(currentDateAndTime)();
}

// 家庭成员表
class FamilyMembers extends Table {
  IntColumn get id => integer().autoIncrement()();
  TextColumn get name => text()();
  TextColumn get avatar => text().nullable()();
  TextColumn get role => text().withDefault(const Constant('member'))();
  DateTimeColumn get createdAt => dateTime().withDefault(currentDateAndTime)();
}

@DriftDatabase(
  tables: [
    Categories,
    Locations,
    Items,
    UsageRecords,
    ShoppingList,
    FamilyMembers,
  ],
)
class AppDatabase extends _$AppDatabase {
  static final AppDatabase _instance = AppDatabase._internal();

  factory AppDatabase() => _instance;

  AppDatabase._internal() : super(_openConnection());
  
  @override
  int get schemaVersion => 1;
  
  Future<void>? _seedDataFuture;
  
  Future<void> ensureInitialized() {
    if (_seedDataFuture == null) {
      _seedDataFuture = seedData();
    }
    return _seedDataFuture!;
  }
  
  static LazyDatabase _openConnection() {
    return LazyDatabase(() async {
      final dbFolder = await getApplicationDocumentsDirectory();
      final file = File(path.join(dbFolder.path, 'homestock.db'));
      return SqfliteQueryExecutor.inDatabaseFolder(path: 'homestock.db');
    });
  }

  // ==================== Categories DAO ====================
  
  // 获取所有顶级分类
  Future<List<Category>> getTopLevelCategories() {
    return (select(categories)
          ..where((c) => c.parentId.isNull())
          ..orderBy([(c) => OrderingTerm(expression: c.sortOrder)]))
        .get();
  }

  // 获取指定父级的子分类
  Future<List<Category>> getChildCategories(int parentId) {
    return (select(categories)
          ..where((c) => c.parentId.equals(parentId))
          ..orderBy([(c) => OrderingTerm(expression: c.sortOrder)]))
        .get();
  }

  // 根据 ID 获取分类
  Future<Category?> getCategoryById(int id) {
    return (select(categories)..where((c) => c.id.equals(id))).getSingleOrNull();
  }

  // ==================== Locations DAO ====================

  // 获取所有顶级位置（房间）
  Future<List<Location>> getTopLevelLocations() {
    return (select(locations)
          ..where((l) => l.parentId.isNull())
          ..orderBy([(l) => OrderingTerm(expression: l.sortOrder)]))
        .get();
  }

  // 获取指定父级的子位置
  Future<List<Location>> getChildLocations(int parentId) {
    return (select(locations)
          ..where((l) => l.parentId.equals(parentId))
          ..orderBy([(l) => OrderingTerm(expression: l.sortOrder)]))
        .get();
  }

  // 根据 ID 获取位置
  Future<Location?> getLocationById(int id) {
    return (select(locations)..where((l) => l.id.equals(id))).getSingleOrNull();
  }

  // 获取所有位置
  Future<List<Location>> getAllLocations() {
    return (select(locations)..orderBy([(l) => OrderingTerm(expression: l.sortOrder)])).get();
  }

  // ==================== Items DAO ====================

  // 获取所有物品（关联分类和位置）
  Future<List<Item>> getAllItems() {
    return (select(items)..orderBy([(i) => OrderingTerm(expression: i.createdAt, mode: OrderingMode.desc)])).get();
  }

  // 根据分类 ID 获取物品
  Future<List<Item>> getItemsByCategory(int categoryId) {
    return (select(items)
          ..where((i) => i.categoryId.equals(categoryId))
          ..orderBy([(i) => OrderingTerm(expression: i.createdAt, mode: OrderingMode.desc)]))
        .get();
  }

  // 根据 ID 获取物品
  Future<Item?> getItemById(int id) {
    return (select(items)..where((i) => i.id.equals(id))).getSingleOrNull();
  }

  // 插入物品并返回 ID
  Future<int> insertItem(ItemsCompanion item) {
    return into(items).insert(item);
  }

  // 更新物品
  Future<bool> updateItem(Item item) {
    return update(items).replace(item);
  }

  // 删除物品（同时清理关联数据）
  Future<void> deleteItem(int id) async {
    await (delete(items)..where((i) => i.id.equals(id))).go();
    // 删除关联的使用记录
    await (delete(usageRecords)..where((r) => r.itemId.equals(id))).go();
    // 清理购物清单中对该物品的关联
    await (update(shoppingList)..where((s) => s.relatedItemId.equals(id)))
        .write(const ShoppingListCompanion(relatedItemId: Value(null)));
  }

  // ==================== UsageRecords DAO ====================

  // 获取物品的使用记录
  Future<List<UsageRecord>> getUsageRecordsByItem(int itemId, {int limit = 10}) {
    return (select(usageRecords)
          ..where((r) => r.itemId.equals(itemId))
          ..orderBy([(r) => OrderingTerm(expression: r.createdAt, mode: OrderingMode.desc)])
          ..limit(limit))
        .get();
  }

  // 插入使用记录
  Future<int> insertUsageRecord(UsageRecordsCompanion record) {
    return into(usageRecords).insert(record);
  }

  // ==================== ShoppingList DAO ====================

  // 获取购物清单
  Future<List<ShoppingListData>> getShoppingList() {
    return (select(shoppingList)
          ..orderBy([(s) => OrderingTerm(expression: s.createdAt, mode: OrderingMode.desc)]))
        .get();
  }

  // 插入购物清单项
  Future<int> insertShoppingListItem(ShoppingListCompanion item) {
    return into(shoppingList).insert(item);
