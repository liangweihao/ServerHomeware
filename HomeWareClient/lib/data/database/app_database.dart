    return MigrationStrategy(
      onCreate: (Migrator m) async {
        await m.createAll();
      },
      onUpgrade: (Migrator m, int from, int to) async {
        if (from < 2) {
          await m.createTable(alertReadStates);
        }
        if (from < 3) {
          await m.addColumn(usageRecords, usageRecords.serverRecordId);
        }
        if (from < 4) {
          await m.addColumn(items, items.serverItemId);
        }
        if (from < 5) {
          await m.addColumn(items, items.salePrice);
        }
        if (from < 6) {
          await m.addColumn(items, items.supplier);
        }
        if (from < 7) {
          await m.createTable(assistantMessages);
        }
      },
    );
  }
  
