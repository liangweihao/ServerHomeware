    try {
      return await (select(items)..orderBy([(i) => OrderingTerm(expression: i.createdAt, mode: OrderingMode.desc)])).get();
    } catch (e) {
      debugPrint('[DB] ERROR: 查询物品列表失败 - $e');
      return <Item>[];
