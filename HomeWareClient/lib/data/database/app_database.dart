  // ==================== FamilyMembers DAO ====================

  // 获取所有家庭成员
  Future<List<FamilyMember>> getFamilyMembers() {
    return (select(familyMembers)..orderBy([(m) => OrderingTerm(expression: m.createdAt)])).get();
  }

  // ==================== Locations Extended DAO ====================

  // 获取位置及其所有子位置
  Future<List<Location>> getLocationAndChildren(int parentId) async {
    final result = <Location>[];
    final children = await getChildLocations(parentId);
    for (final child in children) {
      result.add(child);
      result.addAll(await getLocationAndChildren(child.id));
    }
    return result;
  }

  // 获取位置下的物品数量（包括子位置）
  Future<int> getItemCountForLocation(int locationId) async {
    final location = await getLocationById(locationId);
    if (location == null) return 0;
    
    final childLocations = await getLocationAndChildren(locationId);
    final locationIds = [locationId] + childLocations.map((l) => l.id).toList();
    
    final count = await (select(items)
          ..where((i) => i.locationId.isIn(locationIds)))
        .get();
    
    return count.length;
  }

  // 获取指定位置下的物品（不包括子位置）
  Future<List<Item>> getItemsInLocation(int locationId) {
    return (select(items)
          ..where((i) => i.locationId.equals(locationId))
          ..orderBy([(i) => OrderingTerm(expression: i.expiryDate, mode: OrderingMode.asc)])
          ..where((i) => i.status.equals(0)))
        .get();
  }

  // 插入新位置
  Future<int> insertLocation(LocationsCompanion location) {
    return into(locations).insert(location);
  }

  // 删除位置及其所有子位置
  Future<void> deleteLocationAndChildren(int locationId) async {
    final childLocations = await getLocationAndChildren(locationId);
    final locationIds = [locationId] + childLocations.map((l) => l.id).toList();
    
    await batch((batch) {
      batch.deleteWhere(locations, (l) => l.id.isIn(locationIds));
    });
  }

  // 更新位置排序
  Future<void> updateLocationSortOrder(int locationId, int sortOrder) {
    return (update(locations)..where((l) => l.id.equals(locationId)))
        .write(LocationsCompanion(sortOrder: Value(sortOrder)));
  }

  // ==================== Alerts DAO ====================

  // 获取过期提醒（status=0, 有过期日期, 即将过期）
  Future<List<Item>> getExpiryAlerts() {
    final today = DateTime.now();
    return (select(items)
          ..where((i) => i.status.equals(0))
          ..where((i) => i.expiryDate.isNotNull())
          ..where((i) => i.expiryDate.isSmallerOrEqualValue(today.add(Duration(days: 30)))))
        .get();
  }

  // 获取库存预警（status=0, 库存不足）
  Future<List<Item>> getStockAlerts() {
    return (select(items)
          ..where((i) => i.status.equals(0))
          ..where((i) => i.currentQuantity.isSmallerOrEqual(i.safetyStock)))
        .get();
  }

  // 获取补购提醒（status=1, 最近7天变为用完）
  Future<List<Item>> getRestockAlerts() {
    final sevenDaysAgo = DateTime.now().subtract(const Duration(days: 7));
    return (select(items)
          ..where((i) => i.status.equals(1))
          ..where((i) => i.updatedAt.isBiggerOrEqualValue(sevenDaysAgo)))
        .get();
  }

  // 获取保修提醒（status=0, 保修即将到期）
  Future<List<Item>> getWarrantyAlerts() {
    final today = DateTime.now();
    final thirtyDaysLater = today.add(const Duration(days: 30));
    return (select(items)
          ..where((i) => i.status.equals(0))
          ..where((i) => i.warrantyDate.isNotNull())
          ..where((i) => i.warrantyDate.isBetweenValues(today, thirtyDaysLater)))
        .get();
  }

  // 获取所有提醒数量（过期+库存）
  Future<int> getAlertCount() async {
    final expiryCount = await getExpiryAlerts();
    final stockCount = await getStockAlerts();
    return expiryCount.length + stockCount.length;
  }
  
