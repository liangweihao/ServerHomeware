// 物品表
class Items extends Table {
  IntColumn get id => integer().autoIncrement()();
  TextColumn get name => text()();
  TextColumn get brand => text().nullable()();
  TextColumn get specification => text().nullable()();
  TextColumn get barcode => text().nullable()();
  IntColumn get categoryId => integer()();
  IntColumn get locationId => integer().nullable()();
  RealColumn get purchasePrice => real().nullable()();
  IntColumn get purchaseQuantity => integer().withDefault(const Constant(1))();
  RealColumn get currentQuantity => real().withDefault(const Constant(1))();
  TextColumn get unit => text().withDefault(const Constant('件'))();
  RealColumn get safetyStock => real().withDefault(const Constant(1))();
  DateTimeColumn get purchaseDate => dateTime().nullable()();
  TextColumn get purchaseChannel => text().nullable()();
  DateTimeColumn get productionDate => dateTime().nullable()();
  DateTimeColumn get expiryDate => dateTime().nullable()();
  IntColumn get shelfLifeDays => integer().nullable()();
  DateTimeColumn get openedDate => dateTime().nullable()();
  IntColumn get afterOpenDays => integer().nullable()();
  DateTimeColumn get warrantyDate => dateTime().nullable()();
