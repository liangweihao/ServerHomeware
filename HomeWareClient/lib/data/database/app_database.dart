// 位置表
class Locations extends Table {
  IntColumn get id => integer().autoIncrement()();
  TextColumn get name => text()();
  TextColumn get icon => text().nullable()();
  TextColumn get images => text().nullable()();
  IntColumn get parentId => integer().nullable()();
