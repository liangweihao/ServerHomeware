@DriftDatabase(
  tables: [
    Categories,
    Locations,
    Items,
    UsageRecords,
    ShoppingList,
    FamilyMembers,
  ],
)
class AppDatabase extends _$AppDatabase {
  static final AppDatabase _instance = AppDatabase._internal();

  factory AppDatabase() => _instance;

  AppDatabase._internal() : super(_openConnection());
  
  @override
  int get schemaVersion => 1;
  
  Future<void>? _seedDataFuture;
  
  Future<void> ensureInitialized() {
    if (_seedDataFuture == null) {
      _seedDataFuture = seedData();
    }
    return _seedDataFuture!;
  }
  
  static LazyDatabase _openConnection() {
    return LazyDatabase(() async {
      final dbFolder = await getApplicationDocumentsDirectory();
      final file = File(path.join(dbFolder.path, 'homestock.db'));
      try {
        return SqfliteQueryExecutor.inDatabaseFolder(path: 'homestock.db');
      } catch (e) {
        // 数据库 schema 不匹配（旧版本升级）→ 删除重建
        debugPrint('[DB] WARN: 数据库打开失败，可能是旧版本 schema 不匹配，删除重建 - $e');
        if (await file.exists()) {
          await file.delete();
        }
        return SqfliteQueryExecutor.inDatabaseFolder(path: 'homestock.db');
      }
    });
  }

  // ==================== Categories DAO ====================
  
  // 获取所有顶级分类
  Future<List<Category>> getTopLevelCategories() {
    return (select(categories)
          ..where((c) => c.parentId.isNull())
          ..orderBy([(c) => OrderingTerm(expression: c.sortOrder)]))
        .get();
  }

  // 获取指定父级的子分类
  Future<List<Category>> getChildCategories(int parentId) {
    return (select(categories)
          ..where((c) => c.parentId.equals(parentId))
          ..orderBy([(c) => OrderingTerm(expression: c.sortOrder)]))
        .get();
  }

  // 插入自定义分类
  Future<int> insertCategory(CategoriesCompanion category) {
    return into(categories).insert(category);
  }

  // 根据 ID 获取分类
  Future<Category?> getCategoryById(int id) {
    return (select(categories)..where((c) => c.id.equals(id))).getSingleOrNull();
  }

  // ==================== Locations DAO ====================

  // 获取所有顶级位置（房间）
  Future<List<Location>> getTopLevelLocations() {
    return (select(locations)
          ..where((l) => l.parentId.isNull())
          ..orderBy([(l) => OrderingTerm(expression: l.sortOrder)]))
        .get();
  }

  // 获取指定父级的子位置
  Future<List<Location>> getChildLocations(int parentId) {
    return (select(locations)
          ..where((l) => l.parentId.equals(parentId))
          ..orderBy([(l) => OrderingTerm(expression: l.sortOrder)]))
        .get();
  }

  // 根据 ID 获取位置
  Future<Location?> getLocationById(int id) {
    return (select(locations)..where((l) => l.id.equals(id))).getSingleOrNull();
  }

  // 获取所有位置
  Future<List<Location>> getAllLocations() {
    return (select(locations)..orderBy([(l) => OrderingTerm(expression: l.sortOrder)])).get();
  }

  // ==================== Items DAO ====================

  // 获取所有物品（关联分类和位置）
  Future<List<Item>> getAllItems() async {
    try {
      return await (select(items)..orderBy([(i) => OrderingTerm(expression: i.createdAt, mode: OrderingMode.desc)])).get();
    } catch (e) {
      debugPrint('[DB] ERROR: 查询物品列表失败 - $e');
      return <Item>[];
    }
  }

  // 根据分类 ID 获取物品
  Future<List<Item>> getItemsByCategory(int categoryId) {
    return (select(items)
          ..where((i) => i.categoryId.equals(categoryId))
          ..orderBy([(i) => OrderingTerm(expression: i.createdAt, mode: OrderingMode.desc)]))
        .get();
  }

  // 根据 ID 获取物品
  Future<Item?> getItemById(int id) {
    return (select(items)..where((i) => i.id.equals(id))).getSingleOrNull();
  }

  // 插入物品并返回 ID
  Future<int> insertItem(ItemsCompanion item) {
    return into(items).insert(item);
  }

  // 更新物品
  Future<bool> updateItem(Item item) {
    return update(items).replace(item);
  }

  // 删除物品（同时清理关联数据）
  Future<void> deleteItem(int id) async {
    await (delete(items)..where((i) => i.id.equals(id))).go();
    // 删除关联的使用记录
    await (delete(usageRecords)..where((r) => r.itemId.equals(id))).go();
    // 清理购物清单中对该物品的关联
    await (update(shoppingList)..where((s) => s.relatedItemId.equals(id)))
        .write(const ShoppingListCompanion(relatedItemId: Value(null)));
  }

  // ==================== UsageRecords DAO ====================

  // 获取物品的使用记录
  Future<List<UsageRecord>> getUsageRecordsByItem(int itemId, {int limit = 10}) {
    return (select(usageRecords)
          ..where((r) => r.itemId.equals(itemId))
          ..orderBy([(r) => OrderingTerm(expression: r.createdAt, mode: OrderingMode.desc)])
          ..limit(limit))
        .get();
  }

  // 获取全部最近使用记录（用于同步去重）
  Future<List<UsageRecord>> getRecentUsageRecords({int limit = 1000}) {
    return (select(usageRecords)
          ..orderBy([(r) => OrderingTerm(expression: r.createdAt, mode: OrderingMode.desc)])
          ..limit(limit))
        .get();
  }

  // 插入使用记录
  Future<int> insertUsageRecord(UsageRecordsCompanion record) {
    return into(usageRecords).insert(record);
  }

  // ==================== ShoppingList DAO ====================

  // 获取购物清单
  Future<List<ShoppingListData>> getShoppingList() {
    return (select(shoppingList)
          ..orderBy([(s) => OrderingTerm(expression: s.createdAt, mode: OrderingMode.desc)]))
        .get();
  }

  // 插入购物清单项
  Future<int> insertShoppingListItem(ShoppingListCompanion item) {
    return into(shoppingList).insert(item);
  }

  // ==================== FamilyMembers DAO ====================

  // 获取所有家庭成员
  Future<List<FamilyMember>> getFamilyMembers() {
    return (select(familyMembers)..orderBy([(m) => OrderingTerm(expression: m.createdAt)])).get();
  }

  // ==================== Locations Extended DAO ====================

  // 获取位置及其所有子位置
  Future<List<Location>> getLocationAndChildren(int parentId) async {
    final result = <Location>[];
    final children = await getChildLocations(parentId);
    for (final child in children) {
      result.add(child);
      result.addAll(await getLocationAndChildren(child.id));
    }
    return result;
  }

  // 获取位置下的物品数量（包括子位置）
  Future<int> getItemCountForLocation(int locationId) async {
    final location = await getLocationById(locationId);
    if (location == null) return 0;
    
    final childLocations = await getLocationAndChildren(locationId);
    final locationIds = [locationId] + childLocations.map((l) => l.id).toList();
    
    final count = await (select(items)
          ..where((i) => i.locationId.isIn(locationIds)))
        .get();
    
    return count.length;
  }

  // 获取指定位置下的物品（不包括子位置）
  Future<List<Item>> getItemsInLocation(int locationId) {
    return (select(items)
          ..where((i) => i.locationId.equals(locationId))
          ..orderBy([(i) => OrderingTerm(expression: i.expiryDate, mode: OrderingMode.asc)])
          ..where((i) => i.status.equals(0)))
        .get();
  }

  // 插入新位置
  Future<int> insertLocation(LocationsCompanion location) {
    return into(locations).insert(location);
  }

  // 删除位置及其所有子位置
  Future<void> deleteLocationAndChildren(int locationId) async {
    final childLocations = await getLocationAndChildren(locationId);
    final locationIds = [locationId] + childLocations.map((l) => l.id).toList();
    
    await batch((batch) {
      batch.deleteWhere(locations, (l) => l.id.isIn(locationIds));
    });
  }

  // 更新位置排序
  Future<void> updateLocationSortOrder(int locationId, int sortOrder) {
    return (update(locations)..where((l) => l.id.equals(locationId)))
        .write(LocationsCompanion(sortOrder: Value(sortOrder)));
  }

  // ==================== Alerts DAO ====================

  // 获取过期提醒（status=0, 有过期日期, 即将过期）
  Future<List<Item>> getExpiryAlerts() {
    final today = DateTime.now();
    return (select(items)
          ..where((i) => i.status.equals(0))
          ..where((i) => i.expiryDate.isNotNull())
          ..where((i) => i.expiryDate.isSmallerOrEqualValue(today.add(Duration(days: 30)))))
        .get();
  }

  // 获取库存预警（status=0, 库存不足）
  Future<List<Item>> getStockAlerts() {
    return (select(items)
          ..where((i) => i.status.equals(0))
          ..where((i) => i.currentQuantity.isSmallerOrEqual(i.safetyStock)))
        .get();
  }

  // 获取补购提醒（status=1, 最近7天变为用完）
  Future<List<Item>> getRestockAlerts() {
    final sevenDaysAgo = DateTime.now().subtract(const Duration(days: 7));
    return (select(items)
          ..where((i) => i.status.equals(1))
          ..where((i) => i.updatedAt.isBiggerOrEqualValue(sevenDaysAgo)))
        .get();
  }

  // 获取保修提醒（status=0, 保修即将到期）
  Future<List<Item>> getWarrantyAlerts() {
    final today = DateTime.now();
    final thirtyDaysLater = today.add(const Duration(days: 30));
    return (select(items)
          ..where((i) => i.status.equals(0))
          ..where((i) => i.warrantyDate.isNotNull())
          ..where((i) => i.warrantyDate.isBetweenValues(today, thirtyDaysLater)))
        .get();
  }

  // 获取所有提醒数量（过期+库存）
  Future<int> getAlertCount() async {
    try {
      final expiryCount = await getExpiryAlerts();
      final stockCount = await getStockAlerts();
      return expiryCount.length + stockCount.length;
    } catch (e) {
      debugPrint('[DB] WARN: 获取提醒数量失败 - $e');
      return 0;
    }
  }
  
